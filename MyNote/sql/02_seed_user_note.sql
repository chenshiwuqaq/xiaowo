## 算法

第 k 步：

$$
z_v^{(k)} = \sigma\Big(W^{(k)} \cdot \big[h_v^{(k-1)} \, \| \, \rho\big(\{h_u^{(k-1)}: u \in \mathcal{N}(v)\}\big)\big]\Big)
$$

- $\rho$ 可以是 mean / GCN / LSTM / max-pool；论文实验显示 **pooling 与 GCN 聚合综合最好**，LSTM 慢且提升有限。
- 最后 $z_v^{(K)}$ 过 softmax 做类别预测，训练目标为邻居采样后的多分类交叉熵。

