## 1. 为什么需要图上的表示学习

现实世界大量数据天然是图结构：社交网络、引用网络、分子图、知识图谱、推荐系统中的用户-商品二部图。传统深度模型处理的是欧氏空间上的规则网格（图像、序列），而图的**节点度不固定、没有天然排序**，卷积难以直接套用。

核心问题被归结为：**如何为每个节点学出一个低维向量，使得向量间的距离能反映图上的结构关系与语义关系。**

## 2. 消息传递框架（Message Passing）

大多数 GNN 可以写成一个统一的迭代形式：

$$
h_v^{(k+1)} = \gamma^{(k)}\Big(h_v^{(k)},\ \bigoplus_{u \in \mathcal{N}(v)} \phi^{(k)}(h_u^{(k)}, h_v^{(k)}, e_{uv})\Big)
$$

- $\phi$：消息函数，把邻居信息编码成消息；
- $\bigoplus$：聚合算子，要求对邻居集合置换不变（mean / max / sum / attention）；
- $\gamma$：更新函数，通常是 MLP。

聚合算子的选择直接影响表达能力。sum 聚合能区分邻居数量，max 聚合近似多重集判别，mean 则等价于对度做归一化。

